#!/usr/bin/env python3
"""Static evidence overlay: aligned ROM words that are Thumb pointers (bit0=1) into the
code region whose target begins with a PUSH {..., LR} prologue. Both conditions together
make data-as-code false positives very unlikely. usage: make_pointer_overlay.py rom out.toml"""
import sys, struct, numpy as np
rom=open(sys.argv[1],'rb').read()
w=np.frombuffer(rom,dtype='<u4')
lo,hi=0x08000001,0x08140000
t=np.unique(w[(w>=lo)&(w<hi)&((w&1)==1)])
out=[]
for v in t:
    a=int(v)-1; h=struct.unpack_from('<H',rom,a-0x08000000)[0]
    h2=struct.unpack_from('<H',rom,a+2-0x08000000)[0]
    if (h&0xFF00)==0xB500: out.append(a)
    elif (h&0xFF80)==0xB080 and (h2&0xFF00)==0xB500: out.append(a)   # varargs: SUB SP,#n; PUSH {..LR}
with open(sys.argv[2],'w') as o:
    o.write('# AUTO-GENERATED by tools/make_pointer_overlay.py: data-referenced Thumb functions\n')
    o.write('# (aligned pointer with bit0 set -> target starts with PUSH {...,LR}).\n\n')
    o.write('[identity]\nsha1 = "306fb8874533b0fd0796208faa8bed2db4ae77fb"\n\n')
    for a in out: o.write(f'[[extra_func]]\naddr = 0x{a:08X}\nmode = "thumb"\nnote = "data pointer + push-lr prologue"\n\n')
print(len(out),'entries')
