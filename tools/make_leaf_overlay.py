#!/usr/bin/env python3
"""Static evidence overlay for data-referenced Thumb LEAF functions (no PUSH LR).
Candidate = aligned ROM word that is a Thumb pointer into the code region, target is
4-byte aligned, not already inside any discovered function (dispatch table), and a
linear decode reaches BX/POP{PC} within 96 instructions using only valid Thumb
encodings (no BL into data, no undefined/SWI). usage: rom dispatch_table.cpp out.toml"""
import sys, struct, re, numpy as np
from capstone import Cs, CS_ARCH_ARM, CS_MODE_THUMB
rom=open(sys.argv[1],'rb').read()
tab=set(int(m.group(1),16) for m in re.finditer(r'\{0x([0-9A-F]{8})u, \du, \du,', open(sys.argv[2]).read()))
w=np.frombuffer(rom,dtype='<u4')
t=np.unique(w[(w>=0x08000001)&(w<0x08140000)&((w&1)==1)])
T=Cs(CS_ARCH_ARM,CS_MODE_THUMB)
out=[]
for v in t:
    a=int(v)-1
    if a&3 or a in tab: continue
    ok=False; n=0; off=a-0x08000000
    for ins in T.disasm(rom[off:off+400],a):
        n+=1
        mn=ins.mnemonic
        if mn in ('svc','udf','bkpt') or n>96: break
        if mn=='bx' or (mn=='pop' and 'pc' in ins.op_str) or (mn=='mov' and ins.op_str.startswith('pc')): ok=True; break
        if mn=='bl':
            tgt=int(ins.op_str.lstrip('#'),16)
            if not (0x08000000<=tgt<0x08140000): break
    else:
        ok=False
    if ok: out.append(a)
with open(sys.argv[3],'w') as o:
    o.write('# AUTO-GENERATED by tools/make_leaf_overlay.py: data-referenced Thumb leaf functions.\n\n')
    o.write('[identity]\nsha1 = "306fb8874533b0fd0796208faa8bed2db4ae77fb"\n\n')
    for a in out: o.write(f'[[extra_func]]\naddr = 0x{a:08X}\nmode = "thumb"\nnote = "data pointer + linear leaf decode"\n\n')
print(len(out),'leaf entries')
