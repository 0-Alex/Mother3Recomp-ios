#!/usr/bin/env python3
"""Turn reference-tracer indirect-call targets into a gba_recompile overlay.
usage: make_oracle_overlay.py out.toml entries.txt [more.txt ...]
Each line: 8-hex address with bit0 = Thumb. BIOS (<0x4000) and stack-resident
flash helpers (0x03006000-0x03008000, dispatched by a hook) are skipped."""
import sys
CODE_COPIES=[(0x03000000,0x400),(0x03002EF0,0x800),(0x03005714,0x100),(0x03004C14,0x100),(0x03004D14,0x100)]
out=sys.argv[1]; seen={}
for f in sys.argv[2:]:
    for line in open(f):
        line=line.strip()
        if not line: continue
        v=int(line,16); thumb=v&1; a=v&~1
        if a<0x4000: continue
        if 0x02000000<=a<0x08000000 and not any(s<=a<s+n for s,n in CODE_COPIES): continue
        if a>=0x0A000000: continue
        seen[a]=thumb
with open(out,'w') as o:
    o.write('# AUTO-GENERATED by tools/make_oracle_overlay.py from mGBA reference traces.\n')
    o.write('# Indirect-call (BX non-LR) targets that were not shadow-stack returns.\n\n')
    o.write('[identity]\nsha1 = "306fb8874533b0fd0796208faa8bed2db4ae77fb"\n\n')
    for a in sorted(seen):
        o.write(f'[[extra_func]]\naddr = 0x{a:08X}\nmode = "{"thumb" if seen[a] else "arm"}"\nnote = "oracle indirect target"\n\n')
print(len(seen),'entries ->',out)
