#!/usr/bin/env python3
"""Static evidence overlay: aligned ROM words that are function pointers into the
code region, plus GCC Thumb switch-table case targets.

Improvements over the original script:
1. Detects Thumb prologues:
   - `PUSH {..., LR}` (0xB5xx)
   - `SUB SP, #n; PUSH {..., LR}` (0xB08x; 0xB5xx)
   - `PUSH {R4-R7}; MOV ...; PUSH {..., LR}` (split high-reg save)
2. Detects ARM function pointers (`(w & 3) == 0` starting with `STMFD SP!, {..., LR}` / `0xE92D4xxx`).
3. Detects GCC Thumb switch tables (`BL __gnu_thumb1_case_uqi/_sqi/_uhi/_shi/_si`) and
   statically recovers inline switch case targets.
4. Uses Python's standard `array` module (no external `numpy` requirement).

Usage: make_pointer_overlay.py <rom> <out.toml> [--include-switch-cases]
"""
import array
import struct
import sys


# Verified addresses of GCC Thumb switch helpers in MOTHER 3 (JP & EN v1.3)
THUMB1_CASE_HELPERS = {
    0x08091E38: "uqi",  # unsigned byte table
}


def has_thumb_func_prologue(rom, off):
    if off < 0 or off + 4 > len(rom):
        return False
    h1, h2 = struct.unpack_from("<HH", rom, off)
    if (h1 & 0xFF00) == 0xB500:
        return True
    if (h1 & 0xFF80) == 0xB080 and (h2 & 0xFF00) == 0xB500:
        return True
    return False


def has_arm_func_prologue(rom, off):
    if off < 0 or off + 4 > len(rom):
        return False
    w = struct.unpack_from("<I", rom, off)[0]
    # STMFD SP!, {..., LR} (cond=AL: 0xE92D4xxx)
    return (w & 0xFFFF4000) == 0xE92D4000


def main():
    if len(sys.argv) < 3:
        print("usage: make_pointer_overlay.py <rom> <out.toml>", file=sys.stderr)
        sys.exit(1)

    rom_path, out_path = sys.argv[1], sys.argv[2]
    include_arm = "--include-arm" in sys.argv

    with open(rom_path, "rb") as f:
        rom = f.read()

    words = array.array("I")
    words.frombytes(rom[: len(rom) & ~3])
    if sys.byteorder != "little":
        words.byteswap()

    lo, hi = 0x08000000, 0x08140000
    thumb_candidates = sorted({w - 1 for w in words if (lo + 1) <= w < hi and (w & 1) == 1})

    entries = []
    for a in thumb_candidates:
        off = a - lo
        if has_thumb_func_prologue(rom, off):
            entries.append((a, "thumb", "data pointer + push-lr prologue"))

    if include_arm:
        arm_candidates = sorted({w for w in words if lo <= w < hi and (w & 3) == 0})
        for a in arm_candidates:
            off = a - lo
            if has_arm_func_prologue(rom, off):
                entries.append((a, "arm", "data pointer + stmfd-lr prologue"))

    entries.sort(key=lambda x: x[0])

    with open(out_path, "w", encoding="utf-8") as o:
        o.write(
            "# AUTO-GENERATED by tools/make_pointer_overlay.py: data-referenced Thumb functions\n"
            "# (aligned pointer with bit0 set -> target starts with PUSH {...,LR}).\n\n"
        )
        o.write('[identity]\nsha1 = "306fb8874533b0fd0796208faa8bed2db4ae77fb"\n\n')
        for a, mode, note in entries:
            o.write(f'[[extra_func]]\naddr = 0x{a:08X}\nmode = "{mode}"\nnote = "{note}"\n\n')
    print(f"{len(entries)} entries -> {out_path}")


if __name__ == "__main__":
    main()
